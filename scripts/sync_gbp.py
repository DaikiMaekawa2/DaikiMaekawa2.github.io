#!/usr/bin/env python3
"""Refresh _data/gbp.yml (Google rating + review-count floor) from the
marketing repo's review snapshot.

    python3 scripts/sync_gbp.py          # live pull, rewrite _data/gbp.yml
    python3 scripts/sync_gbp.py --check  # exit 1 if the site overstates

The marketing repo owns the Google Business Profile API client and its
credentials (.env, outside this repo). This script borrows that client to
read the live rating/count, without saving anything back to the marketing
repo, so no API client or credential ever lives in this public repository.
If the live call fails, it falls back to the marketing repo's daily
snapshot (data/gbp_reviews.json, written by its collect_gbp.py).

Only two aggregate figures are published: the average rating (one decimal)
and the review count rounded DOWN to a multiple of 5, shown as "20+", so
the claim stays true as reviews keep coming in. Review quotes are not
copied automatically; they are curated by hand in _data/reviews.yml
(masked names, Japanese translation).

Set NYANMESHI_MARKETING_DIR to point at a different marketing repo checkout.
"""

import json
import os
import sys
from pathlib import Path

import yaml

SITE_DIR = Path(__file__).resolve().parent.parent
MARKETING_DIR = Path(os.environ.get(
    "NYANMESHI_MARKETING_DIR",
    "/home/common/nyanmeshi_business_materials/nyanmeshi_marketing",
))
SNAPSHOT = MARKETING_DIR / "data" / "gbp_reviews.json"
GBP_YML = SITE_DIR / "_data" / "gbp.yml"


def live_snapshot():
    """Read rating/count straight from the GBP API via the marketing repo's
    client. Returns None (with a note) on any failure."""
    try:
        sys.path.insert(0, str(MARKETING_DIR / "scripts"))
        from lib import gbp_api
        import setup_gbp
        env = setup_gbp.load_env()
        token = gbp_api.refresh_access_token(
            env["GBP_CLIENT_ID"], env["GBP_CLIENT_SECRET"], env["GBP_REFRESH_TOKEN"])
        raw = gbp_api.list_reviews(env["GBP_ACCOUNT_ID"], env["GBP_LOCATION_ID"], token)
    except Exception as e:  # network, auth, missing .env: fall back, don't block
        print(f"note: live GBP pull failed ({type(e).__name__}); using the daily snapshot")
        return None
    from datetime import datetime
    return {
        "average_rating": raw.get("averageRating"),
        "total_review_count": raw.get("totalReviewCount", len(raw.get("reviews", []))),
        "collected_at": datetime.now().astimezone().isoformat(),
    }


def derive(snapshot):
    rating = snapshot.get("average_rating")
    count = snapshot.get("total_review_count")
    if rating is None or not count:
        sys.exit(f"{SNAPSHOT} has no rating/count — rerun the marketing GBP collector")
    return {
        "rating": f"{float(rating):.1f}",
        "review_floor": int(count) // 5 * 5,
        "as_of": snapshot.get("collected_at", "")[:10],
    }


def main():
    snapshot = None if "--check" in sys.argv else live_snapshot()
    if snapshot is None:
        if not SNAPSHOT.exists():
            sys.exit(f"review snapshot not found at {SNAPSHOT} — set NYANMESHI_MARKETING_DIR")
        snapshot = json.loads(SNAPSHOT.read_text())
    live = derive(snapshot)

    if "--check" in sys.argv:
        site = yaml.safe_load(GBP_YML.read_text()) if GBP_YML.exists() else {}
        problems = []
        if float(site.get("rating", 0)) > float(live["rating"]):
            problems.append(f"site rating {site['rating']} > live {live['rating']}")
        if int(site.get("review_floor", 0)) > int(live["review_floor"]) + 4:
            problems.append(f"site review floor {site['review_floor']}+ > live count")
        if problems:
            print("gbp.yml OVERSTATES Google: " + "; ".join(problems)
                  + " — run: python3 scripts/sync_gbp.py")
            sys.exit(1)
        print(f"gbp.yml ok (site {site.get('rating')} / {site.get('review_floor')}+, "
              f"live {live['rating']} as of {live['as_of']})")
        return

    GBP_YML.write_text(
        "# GENERATED by scripts/sync_gbp.py from the marketing repo's Google\n"
        "# Business Profile snapshot. Do not edit by hand; rerun the script.\n"
        f"rating: \"{live['rating']}\"\n"
        f"review_floor: {live['review_floor']}\n"
        f"as_of: {live['as_of']}\n"
    )
    print(f"wrote {GBP_YML.relative_to(SITE_DIR)}: {live['rating']} from "
          f"{live['review_floor']}+ reviews (as of {live['as_of']})")


if __name__ == "__main__":
    main()
